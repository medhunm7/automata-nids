/**
 * Database Seeder Script
 * Automatically seeds 100 sample events, 20 suspicious attack events,
 * runs them through the Automata Engine, and inserts alerts & users.
 */

const fs = require('fs');
const path = require('path');
const bcrypt = require('bcryptjs');
const { connectDB } = require('../config/db');
const User = require('../models/User');
const NetworkEvent = require('../models/NetworkEvent');
const Alert = require('../models/Alert');
const { generateSampleEvents } = require('./sampleData');
const { AutomataDetector } = require('../automata/detector');

async function seedDatabase(silent = false) {
  if (!silent) console.log('🌱 [Seeder] Starting database population...');

  await connectDB();

  // 1. Seed Default Users
  const salt = await bcrypt.genSalt(10);
  const hashedPassword = await bcrypt.hash('Admin@12345', salt);
  const analystHashedPassword = await bcrypt.hash('Analyst@12345', salt);

  const existingAdmin = await User.findOne({ email: 'admin@nids.local' });
  if (!existingAdmin) {
    await User.create({
      name: 'Security Admin',
      email: 'admin@nids.local',
      password: hashedPassword,
      role: 'admin'
    });
    if (!silent) console.log('  👤 Created default admin: admin@nids.local / Admin@12345');
  }

  const existingAnalyst = await User.findOne({ email: 'analyst@nids.local' });
  if (!existingAnalyst) {
    await User.create({
      name: 'Cyber Defense Analyst',
      email: 'analyst@nids.local',
      password: analystHashedPassword,
      role: 'analyst'
    });
    if (!silent) console.log('  👤 Created default analyst: analyst@nids.local / Analyst@12345');
  }

  // 2. Clear old events and alerts
  await NetworkEvent.deleteMany({});
  await Alert.deleteMany({});

  // 3. Generate 100 safe + 20 suspicious network events
  const rawEvents = generateSampleEvents();

  // 4. Run events through Automata Detection Engine
  const detector = new AutomataDetector();
  const { processedEvents, alerts, summary } = detector.processBatch(rawEvents);

  // 5. Store processed events in MongoDB
  await NetworkEvent.insertMany(processedEvents);
  if (!silent) console.log(`  📊 Inserted ${processedEvents.length} network events (100 safe + 20 suspicious)`);

  // 6. Store triggered alerts in MongoDB
  await Alert.insertMany(alerts);
  if (!silent) console.log(`  🚨 Stored ${alerts.length} security alerts generated by Automata Engine`);

  // 7. Write sample downloadable files in server/data/
  const dataDir = path.join(__dirname, '../data');
  if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true });
  }

  // CSV
  const csvHeader = 'Timestamp,Source IP,Destination IP,Protocol,Port,Action\n';
  const csvRows = rawEvents.map(e => `${e.timestamp},${e.sourceIP},${e.destinationIP},${e.protocol},${e.port},${e.action}`).join('\n');
  fs.writeFileSync(path.join(dataDir, 'sample_traffic.csv'), csvHeader + csvRows);

  // JSON
  fs.writeFileSync(path.join(dataDir, 'sample_traffic.json'), JSON.stringify(rawEvents, null, 2));

  // TXT
  const txtContent = rawEvents.map(e => `${e.timestamp} ${e.sourceIP} ${e.destinationIP} ${e.protocol} ${e.port} ${e.action}`).join('\n');
  fs.writeFileSync(path.join(dataDir, 'sample_traffic.txt'), txtContent);

  if (!silent) {
    console.log(`  💾 Generated sample downloadable files in server/data/`);
    console.log(`✅ [Seeder] Finished successfully! Summary:`, summary);
  }

  return { summary, alertsCount: alerts.length, eventsCount: processedEvents.length };
}

if (require.main === module) {
  seedDatabase().then(() => {
    process.exit(0);
  }).catch(err => {
    console.error('❌ Seeder error:', err);
    process.exit(1);
  });
}

module.exports = { seedDatabase };
